import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const transpile = source=>ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const uri=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const helpersURL=uri(transpile(readFileSync(new URL('../src/lib/themeDirectives.ts',import.meta.url),'utf8')));
const h=await import(helpersURL);
const assemblySource=readFileSync(new URL('../src/lib/prompt/assemble.ts',import.meta.url),'utf8').replace("'../themeDirectives'",JSON.stringify(helpersURL));
const {assemblePrompt}=await import(uri(transpile(assemblySource)));
const text='장면 본문\n{{theme::밤거리}}';
assert.equal(h.stripThemeDirectives(text),'장면 본문\n');
assert.equal(h.finalThemeDirective(text),'밤거리');
assert.equal(h.finalThemeDirective('{{theme::밤거리}}\n본문'),null);
assert.equal(h.resolveDirectiveTheme('keep',[]),null);
const tag='{{theme::밤거리}}';
for(let i=1;i<=tag.length;i++)assert.equal(h.stripThemeDirectives('본문\n'+tag.slice(0,i),true),'본문\n');
assert.equal(h.stripThemeDirectives('본문 {{일반}}',true),'본문 {{일반}}');
const themes=[{id:'2',name:'밤거리',work_id:'w',owner_id:'a',work_shared:true,ai_prompt:'밤 야외'},
{id:'1',name:'실내',work_id:'w',owner_id:'b',work_shared:false,ai_prompt:'실내'},
{id:'3',name:'비밀',work_id:'w',owner_id:'c',work_shared:false},
{id:'4',name:'다른 작품',work_id:'other',owner_id:'b',work_shared:false}];
const available=h.availableWorkThemes(themes,'w','b');
assert.deepEqual(available.map(t=>t.id),['2','1']);
assert.equal(h.resolveDirectiveTheme('밤거리',available).id,'2');
assert.equal(h.resolveDirectiveTheme('없는 이름',available),null);
assert.equal(h.resolveDirectiveTheme('밤거리',[...available,{...available[0],id:'5'}]),null);
assert.equal(h.themeCatalogPrompt(available),h.themeCatalogPrompt([...available].reverse()));
const input={systemPrompt:'GLOBAL',mainPrompt:'WORK',autoThemeEnabled:true,themePrompt:'THEME RULE',themeCatalog:h.themeCatalogPrompt(available),currentTheme:'실내',history:[{role:'assistant',content:text,cacheBreakpoint:true}],latestUserMessage:'계속',summary:text};
const on=assemblePrompt(input);
assert.equal(on.messages[0].content,text);
assert.equal(on.messages[0].cacheBreakpoint,true);
assert.ok(on.systemParts.core.indexOf('WORK')<on.systemParts.core.indexOf('THEME RULE'));
assert.ok(on.systemParts.core.indexOf('THEME RULE')<on.systemParts.core.indexOf('밤 야외'));
assert.ok(on.systemParts.keywords.includes('실내'));
const off=assemblePrompt({...input,autoThemeEnabled:false});
assert.equal(off.messages[0].content,'장면 본문\n');
assert.equal(off.messages[0].cacheBreakpoint,true);
assert.ok(!JSON.stringify(off).includes('{{theme::'));
assert.ok(!off.systemParts.core.includes('THEME RULE'));
assert.ok(!off.systemParts.core.includes('밤 야외'));
assert.equal(off.systemParts.keywords,'');
assert.equal(input.history[0].content,text);
console.log('Theme directives: stream hiding, raw preservation, scope, names, ON/OFF payload and cache ordering OK');
let state=null;
let observation=h.observeThemeDirective(state,'s',null);state=observation.observation;
assert.equal(observation.changed,false);
observation=h.observeThemeDirective(state,'s',{id:'first',content:text});state=observation.observation;
assert.equal(observation.changed,true,'first generated response applies');
assert.equal(h.observeThemeDirective(state,'s',{id:'first',content:text}).changed,false,'manual theme change does not replay tag');
assert.equal(h.observeThemeDirective(state,'s',{id:'first',content:'edited {{theme::実内}}'}).changed,true,'latest tag edit applies');
assert.equal(h.observeThemeDirective(state,'s',{id:'reroll',content:text}).changed,true,'new selected variant applies');
assert.equal(h.observeThemeDirective(state,'other',{id:'first',content:text}).changed,false,'route change does not replay');
assert.equal(h.observeThemeDirective(null,'s',{id:'first',content:text}).changed,false,'initial load preserves saved manual theme');
console.log('Theme observation lifecycle: first response, edit, reroll, manual choice, reload and navigation OK');
